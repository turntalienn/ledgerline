-- Compatibility with the installed PerfLens diagnostic-evidence snapshot.
-- Evolve the immutable PerfLens V1 baseline with bounded evidence streams,
-- batch metadata, confidence-scored findings, and the current query indexes.

alter table perflens_trace
  add column connection_event_count int not null default 0,
  add column transaction_event_count int not null default 0,
  add column dropped_event_count int not null default 0;

alter table perflens_sql_event
  add column execution_type varchar(20) not null default 'SINGLE',
  add column batch_size int not null default 1;

alter table perflens_finding
  add column confidence varchar(40) null,
  add column recommendation_text text null;

update perflens_finding
set confidence = 'LOW'
where confidence is null;

update perflens_finding
set recommendation_text = ''
where recommendation_text is null;

alter table perflens_finding
  alter column confidence set not null,
  alter column recommendation_text set not null;

create table perflens_connection_event (
  id bigint generated by default as identity primary key,
  trace_id varchar(36) not null,
  span_id varchar(36) not null,
  ordinal_value int not null,
  event_type varchar(60) not null,
  duration_ms double precision not null,
  pool_name varchar(160) null,
  error_message text null
);

create table perflens_transaction_event (
  id bigint generated by default as identity primary key,
  trace_id varchar(36) not null,
  span_id varchar(36) not null,
  ordinal_value int not null,
  transaction_name varchar(300) null,
  new_transaction boolean not null,
  nested_transaction boolean not null,
  read_only boolean not null,
  rollback_only boolean not null,
  duration_ms double precision not null,
  outcome varchar(40) not null,
  error_message text null
);

create index idx_perflens_trace_started_at on perflens_trace(started_at);

-- Add optional HikariCP point-in-time evidence to connection events.
-- Null means the DataSource was not HikariCP or its management API was unavailable.

alter table perflens_connection_event
  add column pool_active int null,
  add column pool_idle int null,
  add column pool_pending int null,
  add column pool_total int null,
  add column pool_max int null;

-- Versioned latency distributions used by rolling-window regression analysis.

create table perflens_latency_baseline (
  target_key varchar(160) not null,
  baseline_version varchar(100) not null,
  sample_count int not null,
  minimum_ms double precision not null,
  mean_ms double precision not null,
  p50_ms double precision not null,
  p95_ms double precision not null,
  p99_ms double precision not null,
  maximum_ms double precision not null,
  created_at timestamp not null,
  activated_at timestamp null,
  active boolean not null default false,
  primary key (target_key, baseline_version)
);

create index idx_perflens_connection_trace_ordinal on perflens_connection_event (trace_id, ordinal_value);
create index idx_perflens_transaction_trace_ordinal on perflens_transaction_event (trace_id, ordinal_value);
create index idx_perflens_latency_baseline_active on perflens_latency_baseline (target_key, active, created_at);
